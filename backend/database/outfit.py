from database.db import get_connection


def save_generated_outfits(
    outfits: list,
    user_id: int = 1,
):
    if not outfits:
        return []

    connection = get_connection()
    cursor = connection.cursor()

    saved_outfits = []

    try:
        for outfit in outfits:

            # ====================================================
            # 1. SAVE OUTFIT
            #    MySQL generates the AUTO_INCREMENT ID
            # ====================================================

            outfit_query = """
                INSERT INTO outfits (
                    user_id,
                    title,
                    recommendation_score,
                    is_generated,
                    is_saved
                )
                VALUES (
                    %s,
                    %s,
                    %s,
                    TRUE,
                    FALSE
                )
            """

            cursor.execute(
                outfit_query,
                (
                    user_id,
                    outfit.get(
                        "title",
                        "AI Outfit",
                    ),
                    outfit.get(
                        "score",
                    ),
                ),
            )

            # Get the ID generated by MySQL
            outfit_id = cursor.lastrowid

            # ====================================================
            # 2. SAVE OUTFIT ITEMS
            # ====================================================

            items = outfit.get(
                "items",
                [],
            )

            for display_order, item in enumerate(
                items
            ):

                clothing_id = item.get(
                    "id"
                )

                if clothing_id is None:
                    continue

                category = item.get(
                    "category",
                    "",
                )

                # Convert category into outfit role
                if category_group_for_role(category) == "upper":
                    role = "upper"

                elif category_group_for_role(category) == "lower":
                    role = "lower"

                elif category_group_for_role(category) == "full":
                    role = "full"

                else:
                    role = category

                item_query = """
                    INSERT INTO outfit_items (
                        outfit_id,
                        clothing_id,
                        role,
                        display_order
                    )
                    VALUES (
                        %s,
                        %s,
                        %s,
                        %s
                    )
                """

                cursor.execute(
                    item_query,
                    (
                        outfit_id,
                        clothing_id,
                        role,
                        display_order,
                    ),
                )

            # ====================================================
            # 3. RETURN OUTFIT WITH GENERATED ID
            # ====================================================

            saved_outfit = dict(outfit)

            saved_outfit["id"] = outfit_id
            saved_outfit["user_id"] = user_id

            saved_outfits.append(
                saved_outfit
            )

        connection.commit()

        print(
            f"✓ Saved {len(saved_outfits)} generated outfits to MySQL."
        )

        return saved_outfits

    except Exception:
        connection.rollback()
        raise

    finally:
        cursor.close()
        connection.close()


def update_outfit_preview(
    outfit_id: int,
    image_url: str,
):
    connection = get_connection()
    cursor = connection.cursor()

    try:
        query = """
            UPDATE outfits
            SET image_url = %s
            WHERE id = %s
        """

        cursor.execute(
            query,
            (
                image_url,
                outfit_id,
            ),
        )

        connection.commit()

    except Exception:
        connection.rollback()
        raise

    finally:
        cursor.close()
        connection.close()


def category_group_for_role(
    category: str,
) -> str:

    category = (
        category or ""
    ).lower().strip()

    if category in {
        "upper",
        "top",
        "shirt",
        "t-shirt",
        "blouse",
        "sweater",
        "jacket",
        "coat",
    }:
        return "upper"

    if category in {
        "lower",
        "pants",
        "trousers",
        "jeans",
        "shorts",
        "skirt",
    }:
        return "lower"

    if category in {
        "full",
        "dress",
        "jumpsuit",
    }:
        return "full"

    return category


def find_existing_outfit(
    clothing_ids: list,
    user_id: int = 1,
):
    if not clothing_ids:
        return None

    connection = get_connection()
    cursor = connection.cursor(dictionary=True)

    try:
        placeholders = ", ".join(
            ["%s"] * len(clothing_ids)
        )

        query = f"""
            SELECT
                o.id,
                o.image_url,
                o.title,
                o.recommendation_score,
                o.created_at,
                fb.feedback

            FROM outfits o

            LEFT JOIN outfit_feedback fb
                ON fb.outfit_id = o.id
                AND fb.user_id = %s

            INNER JOIN outfit_items oi
                ON oi.outfit_id = o.id

            WHERE o.user_id = %s
              AND oi.clothing_id IN ({placeholders})

            GROUP BY
                o.id,
                o.image_url,
                o.title,
                o.recommendation_score,
                o.created_at,
                fb.feedback

            HAVING COUNT(DISTINCT oi.clothing_id) = %s
               AND COUNT(DISTINCT oi.clothing_id) = (
                   SELECT COUNT(*)
                   FROM outfit_items oi2
                   WHERE oi2.outfit_id = o.id
               )

            ORDER BY o.created_at DESC

            LIMIT 1
        """

        values = (
            [user_id, user_id]
            + clothing_ids
            + [len(clothing_ids)]
        )

        cursor.execute(
            query,
            values,
        )

        return cursor.fetchone()

    finally:
        cursor.close()
        connection.close()